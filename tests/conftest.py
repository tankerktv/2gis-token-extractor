"""Общая подготовка тестов.

Пакет лежит в ``src/`` и в тестовом окружении не установлен: ставить его
означало бы тянуть Playwright — сотню мегабайт браузерного хозяйства ради
проверок, которые браузера не касаются вовсе. Поэтому каталоги просто
добавляются в путь импорта.

Тесты нарочно покрывают только то, что ломается молча: опознание токена,
разбор адреса сокета, разбор ответа профиля, выбор путей и коды возврата.
Сам браузер не проверяется — его поведение задаёт 2ГИС, и тест здесь
проверял бы Playwright, а не нас.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

for path in (ROOT / "src", ROOT):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))
